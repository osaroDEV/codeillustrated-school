// Generates the course catalogue seed migration from lib/course-catalog.ts.
//
//   node scripts/generate-course-seed.mjs > supabase/migrations/20261029000300_seed_courses.sql
//
// Only needed again if STATIC_COURSES changes before the seed is applied; once
// the catalogue lives in the database, edit courses through the admin panel.

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const catalogPath = fileURLToPath(new URL("../lib/course-catalog.ts", import.meta.url));
const { outputText } = ts.transpileModule(readFileSync(catalogPath, "utf8"), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
});

const module = { exports: {} };
new Function("module", "exports", "require", outputText)(module, module.exports, () => ({}));
const { STATIC_COURSES } = module.exports;

const q = (value) => `'${String(value).replace(/'/g, "''")}'`;
const lines = [
  "-- Generated by scripts/generate-course-seed.mjs from lib/course-catalog.ts.",
  "-- Idempotent: re-running inserts nothing for courses/modules that exist.",
  "",
];

STATIC_COURSES.forEach((course, index) => {
  lines.push(
    `insert into public.courses (id, title, description, full_description, age, level, duration, icon, color, bg, position, is_published)`,
    `values (${[
      course.id,
      course.title,
      course.description,
      course.fullDescription,
      course.age,
      course.level,
      course.duration,
      course.icon,
      course.color,
      course.bg,
    ]
      .map(q)
      .join(", ")}, ${index + 1}, true)`,
    `on conflict (id) do nothing;`,
    "",
    `insert into public.offerings (course_id, kind, price_usd, price_ngn) values`,
    // 1-on-1 classes are no longer sold; the committed seed migration still
    // inserts those rows, which the app now ignores.
    `  (${q(course.id)}, 'cohort_group', ${course.price.group.usd}, ${course.price.group.ngn})`,
    `on conflict (course_id, kind) do nothing;`,
    ""
  );

  course.curriculum.forEach((mod, modIndex) => {
    lines.push(
      `with m as (`,
      `  insert into public.course_modules (course_id, title, position)`,
      `  values (${q(course.id)}, ${q(mod.module)}, ${modIndex + 1})`,
      `  on conflict (course_id, position) do nothing`,
      `  returning id`,
      `)`,
      `insert into public.lessons (module_id, title, position)`,
      `select m.id, t.title, t.ord`,
      `from m, unnest(array[${mod.lessons.map(q).join(", ")}]) with ordinality as t (title, ord);`,
      ""
    );
  });
});

lines.push(
  "-- Now that every existing course_id has a matching course, link the legacy",
  "-- text columns to it. NOT VALID skips checking pre-existing rows so a stray",
  "-- legacy id can't block the migration; new rows are checked.",
  "do $$",
  "begin",
  ...[
    ["enrollments", "enrollments_course_id_fkey"],
    ["invite_codes", "invite_codes_course_id_fkey"],
    ["announcements", "announcements_course_id_fkey"],
  ].flatMap(([table, name]) => [
    `  if not exists (select 1 from pg_constraint where conname = '${name}') then`,
    `    alter table public.${table} add constraint ${name}`,
    `      foreign key (course_id) references public.courses (id) not valid;`,
    `  end if;`,
  ]),
  "end $$;",
  ""
);

process.stdout.write(lines.join("\n"));
